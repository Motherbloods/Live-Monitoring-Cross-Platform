import { useAppStore } from '../../store/appStore.js'

export default function Toasts() {
  const toasts = useAppStore((s) => s.toasts)
  return (
    <div className="toasts" role="status" aria-live="polite">
      {toasts.map((t) => (
        <div key={t.id} className={`toast toast-${t.tone}`}>
          {t.message}
        </div>
      ))}
    </div>
  )
}
